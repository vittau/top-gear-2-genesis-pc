#!/usr/bin/env python3
"""Recover IRQ roots from stock ROM MOVE.L #handler,RAM-vector writes.

Writes addresses only, never ROM bytes. Audit with tools/disasm_tg2.py.
Requires capstone (same environment as disasm_tg2.py).
"""
import argparse
from pathlib import Path
from capstone import Cs, CS_ARCH_M68K, CS_MODE_BIG_ENDIAN, CS_MODE_M68K_000
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--rom', type=Path, default=Path.home() / 'roms/genesis/tg2.bin')
p.add_argument('--output', type=Path)
a = p.parse_args()
r = a.rom.read_bytes()
md = Cs(CS_ARCH_M68K, CS_MODE_BIG_ENDIAN | CS_MODE_M68K_000)
roots = {}
for pc in range(0x200, len(r) - 10, 2):
    if r[pc:pc+2] != bytes.fromhex('23fc'):
        continue
    dest = int.from_bytes(r[pc+6:pc+10], 'big')
    if dest not in (0xFF01EC, 0xFFFA00):
        continue
    target = int.from_bytes(r[pc+2:pc+6], 'big')
    assert target % 2 == 0 and 0x200 <= target < len(r)
    store = list(md.disasm(r[pc:pc+10], pc))
    entry = next(md.disasm(r[target:target+16], target))
    assert len(store) == 1 and store[0].mnemonic == 'move.l'
    # Genuine ISR prologue or bare RTE, including raster MOVE.W (a5)+,(a6).
    assert entry.mnemonic in ('movem.l', 'movem.w', 'rte', 'move.w')
    roots.setdefault(target, []).append(pc)
lines = ['# IRQ roots: immediate stores to installed RAM JMP operand fields.',
         '# Generated by tools/discover_irqs.py; independently raw-ROM validated.',
         '[functions]', 'extra = [']
for target, sites in sorted(roots.items()):
    lines.append('  # MOVE.L installer sites: ' + ', '.join(f'${s:06X}' for s in sites))
    lines.append(f'  0x{target:06X},')
lines.append(']')
text = '\n'.join(lines) + '\n'
if a.output:
    a.output.write_text(text)
else:
    print(text, end='')
