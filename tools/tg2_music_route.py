#!/usr/bin/env python3
"""Emit the SOUND -> MUSIC TEST route as both back ends' input scripts.

The port and the reference renderer (tools/gpgx_render.c) must receive the
identical controller timeline for their recordings to be comparable, so this
tool owns the timeline and writes it twice:

  --port-script OUT.txt   the runner's text script (WAIT/PRESS/HOLD/RELEASE)
  --gpgx-script OUT.json  the exact-wall-frame JSON (frame, keys) timeline

Route: title screen -> START -> main menu -> DOWN DOWN START (SOUND) ->
DOWN (MUSIC TEST) -> START -> UP x song -> START (play) -> free run.

The page value at $FF2562 is the selected song index (0-based); the row shows
`value + 1`. Only controller input is used: nothing writes guest memory.

  python3 tools/tg2_music_route.py --song 0 --frames 4000 \
      --port-script build/music0/route.txt --gpgx-script build/music0/route.json
"""
from __future__ import annotations

import argparse
import json

# Genesis pad bits (same order as tg2_runner.KEYS / the runner's input script)
KEYS = {'UP': 0x01, 'DOWN': 0x02, 'LEFT': 0x04, 'RIGHT': 0x08,
        'B': 0x10, 'C': 0x20, 'A': 0x40, 'START': 0x80}

TITLE_STEADY = 400
MENU_SETTLE = 200


def timeline(song: int) -> list[tuple[int, int, str]]:
    """[(start_frame, frames_held, keys)] for the whole route."""
    steps: list[tuple[int, int, str]] = []
    f = 0

    def wait(n):
        nonlocal f
        f += n

    def press(keys, frames=6):
        nonlocal f
        steps.append((f, frames, keys))
        f += frames + 2

    wait(TITLE_STEADY)
    press('START', 8)                  # title -> main menu
    wait(MENU_SETTLE)
    press('DOWN'); wait(40)            # 1P GAME -> DIFFICULTY
    press('DOWN'); wait(40)            # DIFFICULTY -> SOUND
    press('START', 8)                  # SOUND submenu
    wait(MENU_SETTLE)
    press('DOWN'); wait(60)            # RACE SOUND -> MUSIC TEST
    press('START', 8)                  # MUSIC TEST page
    wait(MENU_SETTLE)
    for _ in range(song):
        press('UP'); wait(60)          # value 0 -> song index
    press('START', 8)                  # play the selected song
    return steps


def port_script(steps, frames: int) -> str:
    out = ['# Generated by tools/tg2_music_route.py -- input only.']
    cur = 0
    for start, held, keys in steps:
        if start > cur:
            out.append('WAIT %d' % (start - cur))
            cur = start
        out.append('PRESS %s %d' % (keys, held))
        cur += held
    if frames > cur:
        out.append('WAIT %d' % (frames - cur))
    return '\n'.join(out) + '\n'


def gpgx_script(steps, frames: int) -> str:
    events = [{'frame': 0, 'keys': '0'}]
    for start, held, keys in steps:
        events.append({'frame': start, 'keys': '%02X' % KEYS[keys]})
        events.append({'frame': start + held, 'keys': '0'})
    events.append({'frame': frames, 'shot': 'end'})
    return json.dumps(events, indent=1) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--song', type=int, default=0,
                    help='MUSIC TEST song index (0-based; the row shows +1)')
    ap.add_argument('--frames', type=int, default=4000,
                    help='total frames to script (the free run after START)')
    ap.add_argument('--port-script')
    ap.add_argument('--gpgx-script')
    ap.add_argument('--music-test-frame', action='store_true',
                    help='print the frame the MUSIC TEST page opens at')
    a = ap.parse_args()
    steps = timeline(a.song)
    if a.music_test_frame:
        print(sum(h + 2 for _s, h, _k in steps[:-1]) + TITLE_STEADY)
    if a.port_script:
        open(a.port_script, 'w').write(port_script(steps, a.frames))
    if a.gpgx_script:
        open(a.gpgx_script, 'w').write(gpgx_script(steps, a.frames))
    if not a.port_script and not a.gpgx_script:
        print(port_script(steps, a.frames))


if __name__ == '__main__':
    main()
